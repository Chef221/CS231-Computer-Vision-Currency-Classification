"""Copy the audited SVM/KNN figures used by the RGB224 SVM report."""

from __future__ import annotations

import hashlib
import json
import shutil
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = Path(__file__).resolve().parent / "SVM224_FIGURES"
FIGURES = {
    "SVM_1_RESIZE.png": "src/SVM/results_224/inputs/rgb224_examples.png",
    "SVM_2_HOG.png": "src/SVM/results_224/hog/hog_example.png",
    "SVM_3_PCA.png": "src/SVM/results_224/hog_pca/pca_variance.png",
    "SVM_4_CONFUSION_TEST.png": "src/SVM/results_224/test_final/confusion_matrix_test.png",
    "SVM_5_ERROR_CASES.png": "src/SVM/results_224/error_analysis/cases_page_03.png",
    "SVM_6_KNN_REFERENCE.png": "docs/KNN_REPORT/KNN224_FIGURES/KNN_3_CONFUSION_TEST.png",
}


def digest(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    provenance = {
        "method": "Copy figures already generated by the notebooks and KNN report.",
        "script": "docs/SVM_REPORT/build_figures_224.py",
        "figures": {},
    }
    for name, relative_source in FIGURES.items():
        source = ROOT / relative_source
        if not source.is_file():
            raise FileNotFoundError(source)
        destination = OUTPUT / name
        shutil.copy2(source, destination)
        provenance["figures"][name] = {
            "source": relative_source,
            "sha256": digest(destination),
            "bytes": destination.stat().st_size,
        }
        if digest(source) != provenance["figures"][name]["sha256"]:
            raise ValueError(f"Figure copy differs from source: {name}")
    (OUTPUT / "provenance.json").write_text(
        json.dumps(provenance, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"Prepared {len(FIGURES)} figures in {OUTPUT}")


if __name__ == "__main__":
    main()
